# 元话语检查表
BANNED = ["我的理解是", "我的看法是", "我的读法是", "我的观点是", "我的判断是",
          "我试着", "要是让我", "所以你该记住的是", "综上所述", "值得注意的是"]


def check(text):
    hits = [b for b in BANNED if b in text]
    # 标签 + 冒号/逗号 引出结论
    for seg in text.split("\n\n"):
        if "：" in seg and any(k in seg.split("：")[0] for k in ["我", "所以", "这说明", "三层"]):
            hits.append("标签+冒号:" + seg.split("：")[0][:14])
    return hits


hit = 0
